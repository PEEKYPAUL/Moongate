import 'dart:convert';
import 'dart:math' as math;
import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';

import 'package:moongate/services/gcode_layer_parser.dart';

// The layer viewer's parser (v0.9.72): extrusion segments per layer, each
// tagged with the fan, hotend target, speed and flow in force, plus a time
// per layer. Real slicer shapes are exercised: Orca / PrusaSlicer
// LAYER_CHANGE markers, Cura's LAYER:, the Z heuristic when no markers exist,
// PRINT_START temperature arguments, M106 with and without P, relative E,
// arcs, the filament diameter comment.
Uint8List _b(String s) => Uint8List.fromList(utf8.encode(s));

void main() {
  group('parseGcode', () {
    test('Orca-style file: markers, fan bands, PRINT_START temperature', () {
      final m = parseGcode(_b('''
; generated by OrcaSlicer
; thumbnail begin 32x32 100
; iVBORw0KGgo=
; thumbnail end
M190 S100
PRINT_START EXTRUDER_TEMP=255 BED_TEMP=100 CHAMBER=45
G90
M83
;LAYER_CHANGE
;Z:0.2
G1 Z0.2 F600
G1 X10 Y10 F3000
G1 X20 Y10 E1.0
G1 X20 Y20 E1.0
M106 S127.5
;LAYER_CHANGE
;Z:0.4
G1 Z0.4
G1 X10 Y10 ; travel
G1 X20 Y10 E1.0
M106 P2 S255 ; aux fan, ignored
G1 X20 Y20 E1.0
M107
G1 X10 Y20 E1.0
'''));
      expect(m.markers, isTrue);
      expect(m.layers.length, 2);
      expect(m.layers[0].z, closeTo(0.2, 1e-9));
      expect(m.layers[0].segmentCount, 2);
      expect(m.layers[0].fan, everyElement(0.0));
      expect(m.layers[0].temp, everyElement(255.0));
      expect(m.layers[1].z, closeTo(0.4, 1e-9));
      expect(m.layers[1].segmentCount, 3);
      expect(m.layers[1].fan[0], closeTo(0.5, 1e-6));
      expect(m.layers[1].fan[1], closeTo(0.5, 1e-6)); // P2 did not touch it
      expect(m.layers[1].fan[2], 0.0); // M107
      expect(m.fanMax, closeTo(0.5, 1e-6));
      expect(m.tempMin, 255);
      expect(m.tempMax, 255);
      expect(m.minX, 10);
      expect(m.maxX, 20);
      expect(m.maxY, 20);
    });

    test('speed, flow and layer time', () {
      // F3000 = 50 mm/s. 10 mm at 1 mm of 1.75 filament: 2.405 mm³ over
      // 0.2 s = 12.03 mm³/s. The layer also has a 10 mm travel (0.2 s).
      final m = parseGcode(_b('''
; filament_diameter = 1.75
G90
M83
G1 X0 Y0 Z0.2 F3000
G1 X10 Y0 E1
G1 X20 Y0
G1 X20 Y10 E1 F6000
'''));
      final l = m.layers[0];
      expect(l.segmentCount, 2);
      expect(l.speed[0], closeTo(50, 1e-6));
      expect(l.speed[1], closeTo(100, 1e-6));
      const area = math.pi * 0.875 * 0.875;
      expect(l.flow[0], closeTo(area * 50 / 10, 1e-4));
      expect(l.flow[1], closeTo(area * 100 / 10, 1e-4));
      // time: 10/50 + 10/50 (travel) + 10/100 = 0.5 s. The first move (to
      // Z 0.2, before any layer exists) has no layer to book to.
      expect(l.time, closeTo(0.5, 1e-3));
      expect(m.speedMin, closeTo(50, 1e-6));
      expect(m.speedMax, closeTo(100, 1e-6));
      expect(m.timeMin, m.timeMax);
    });

    test('M104 S0 before PRINT_START does not hide the macro temperature', () {
      // The seat file: Orca's "stop the slicer injecting temp waits" trick,
      // then the real value as a macro argument.
      final m = parseGcode(_b('''
M104 S0 ; stops the slicer injecting its own temp waits
M140 S0
PRINT_START HOTEND=260 BED=120
G90
M83
G1 X0 Y0 Z0.2 F3000
G1 X10 Y0 E1
M104 S250
G1 X20 Y0 E1
'''));
      expect(m.layers[0].temp[0], 260);
      expect(m.layers[0].temp[1], 250); // a later explicit M104 still wins
      expect(m.tempMin, 250);
      expect(m.tempMax, 260);
    });

    test('a 2.85 filament diameter changes the flow', () {
      final m = parseGcode(_b('''
; filament_diameter = 2.85
G90
M83
G1 X0 Y0 Z0.2 F3000
G1 X10 Y0 E1
'''));
      const area = math.pi * 1.425 * 1.425;
      expect(m.layers[0].flow[0], closeTo(area * 50 / 10, 1e-4));
    });

    test('travels, retractions and wipes are not segments', () {
      final m = parseGcode(_b('''
G90
M82
G1 X0 Y0 Z0.2
G1 X10 Y0 E1
G1 E0.2 ; retract
G1 X20 Y0 ; travel, no E
G1 X30 Y0 E0.1 ; wipe-ish: E below the last value -> not extruding
G1 X40 Y0 E2 ; extrudes again
'''));
      expect(m.layers.length, 1);
      expect(m.layers[0].segmentCount, 2);
      final p = m.layers[0].points;
      expect(p[0], 0);
      expect(p[2], 10);
      expect(p[4], 30);
      expect(p[6], 40);
    });

    test('no markers: the Z heuristic builds layers and ignores z-hop', () {
      final m = parseGcode(_b('''
G90
M83
M104 S240
G1 X0 Y0 Z0.3
G1 X10 Y0 E1
G1 Z0.8 ; z-hop travel
G1 X20 Y0
G1 Z0.3
G1 X30 Y0 E1
G1 Z0.6
G1 X40 Y0 E1
M104 S230
G1 X50 Y0 E1
'''));
      expect(m.markers, isFalse);
      expect(m.layers.length, 2);
      expect(m.layers[0].z, closeTo(0.3, 1e-9));
      expect(m.layers[0].segmentCount, 2);
      expect(m.layers[1].z, closeTo(0.6, 1e-9));
      expect(m.layers[1].temp[0], 240);
      expect(m.layers[1].temp[1], 230);
      expect(m.tempMin, 230);
      expect(m.tempMax, 240);
    });

    test('Cura LAYER: markers and M109 with a tool', () {
      final m = parseGcode(_b('''
;FLAVOR:Marlin
;LAYER_COUNT:2
M109 S215 T0
G90
M82
;LAYER:0
G0 X0 Y0 Z0.2
G1 X10 Y0 E1
;LAYER:1
G0 Z0.4
G1 X10 Y10 E2
'''));
      expect(m.markers, isTrue);
      expect(m.layers.length, 2);
      expect(m.layers[1].segmentCount, 1);
      expect(m.layers[1].temp[0], 215);
    });

    test('SET_HEATER_TEMPERATURE and G2 arcs', () {
      final m = parseGcode(_b('''
SET_HEATER_TEMPERATURE HEATER=extruder TARGET=250
G90
M83
G1 X0 Y0 Z0.2 F1200
G2 X10 Y10 I10 J0 E1
'''));
      expect(m.layers.length, 1);
      // A 90 degree arc in 5 degree steps = 18 segments.
      expect(m.layers[0].segmentCount, 18);
      expect(m.layers[0].temp[0], 250);
      final p = m.layers[0].points;
      // Ends exactly on the commanded end point.
      expect(p[p.length - 2], closeTo(10, 1e-6));
      expect(p[p.length - 1], closeTo(10, 1e-6));
      // Flow spread over the arc length (quarter circle of r 10).
      const arcLen = math.pi * 10 / 2;
      const area = math.pi * 0.875 * 0.875;
      expect(m.layers[0].flow[0], closeTo(area * 20 / arcLen, 1e-4));
    });

    test('CRLF line endings and an empty file', () {
      final m = parseGcode(_b('G90\r\nM83\r\nG1 X0 Y0 Z0.2\r\nG1 X5 Y0 E1\r\n'));
      expect(m.layers.length, 1);
      expect(m.layers[0].segmentCount, 1);
      final e = parseGcode(Uint8List(0));
      expect(e.layers, isEmpty);
      expect(e.height, 0);
    });

    test('decimateSegments merges straight chains, keeps corners and bands', () {
      // Five 1 mm steps along X (collinear), then a 90 degree corner up Y,
      // then two more steps along Y at a different fan value.
      final pts = Float32List.fromList([
        0, 0, 1, 0, 1, 0, 2, 0, 2, 0, 3, 0, 3, 0, 4, 0, 4, 0, 5, 0, // chain A
        5, 0, 5, 1, 5, 1, 5, 2, // corner, chain B (same fan)
        5, 2, 5, 3, 5, 3, 5, 4, // chain C (other fan)
      ]);
      final fan = Float32List.fromList([1, 1, 1, 1, 1, 1, 1, 0, 0]);
      final d = decimateSegments(pts, fan,
          lo: 0, hi: 1, bands: 16, maxLen: 10, tol: 0.05);
      expect(d.$2.length, 3);
      expect(d.$1.sublist(0, 4), [0, 0, 5, 0]); // A as one chord
      expect(d.$1.sublist(4, 8), [5, 0, 5, 2]); // B
      expect(d.$1.sublist(8, 12), [5, 2, 5, 4]); // C
      expect(d.$2, [1, 1, 0]);
      // maxLen splits a long straight chain.
      final short = decimateSegments(pts, fan,
          lo: 0, hi: 1, bands: 16, maxLen: 2, tol: 0.05);
      expect(short.$2.length, greaterThan(3));
      // A gentle arc: 36 chords of 10 degrees on a 10 mm radius merge while
      // the sagitta stays under tol, so a loose tol merges more than a tight one.
      final arc = <double>[];
      for (var i = 0; i < 36; i++) {
        final a0 = i * 10 * 3.14159265 / 180, a1 = (i + 1) * 10 * 3.14159265 / 180;
        arc.addAll([
          10 * math.cos(a0), 10 * math.sin(a0), 10 * math.cos(a1), 10 * math.sin(a1)
        ]);
      }
      final arcP = Float32List.fromList(arc);
      final arcV = Float32List(36);
      final tight = decimateSegments(arcP, arcV,
          lo: 0, hi: 1, bands: 16, maxLen: 100, tol: 0.05);
      final loose = decimateSegments(arcP, arcV,
          lo: 0, hi: 1, bands: 16, maxLen: 100, tol: 0.5);
      expect(tight.$2.length, 36); // 10 degree chords already exceed 0.05
      expect(loose.$2.length, lessThan(18));
    });

    test('relative XYZ (G91) accumulates', () {
      final m = parseGcode(_b('''
G90
G1 X10 Y10 Z0.2
G91
M83
G1 X5 E1
G1 Y5 E1
'''));
      final p = m.layers[0].points;
      expect(p[2], 15);
      expect(p[5], 10);
      expect(p[7], 15);
    });

    // ── Tools and colours (v0.9.73, the Colour view) ─────────────────────

    test('two-tool Orca file: tool per segment, colours and types from the settings block', () {
      final m = parseGcode(_b('''
; generated by OrcaSlicer
G90
M83
T0
;LAYER_CHANGE
;Z:0.2
G1 Z0.2 F600
G1 X10 Y10 F3000
G1 X20 Y10 E1.0
; CP TOOLCHANGE START
T1
G1 X30 Y10 E0.5 ; wipe tower, drawn in T1
; CP TOOLCHANGE END
G1 X30 Y20 E1.0
T0
G1 X10 Y20 E1.0
; CONFIG_BLOCK_START
; filament_colour = #8B4A2F;#1A1A1A
; filament_diameter = 1.75,1.75
; filament_type = PLA;PETG
; filament_type_extra = ignored
; CONFIG_BLOCK_END
'''));
      expect(m.layers.length, 1);
      expect(m.layers[0].tool, [0, 1, 1, 0]);
      expect(m.isMultiTool, isTrue);
      expect(m.hasSlicerColours, isTrue);
      expect(m.tools.length, 2);
      expect(m.tools[0].index, 0);
      expect(m.tools[0].argb, 0xFF8B4A2F);
      expect(m.tools[0].type, 'PLA');
      expect(m.tools[1].index, 1);
      expect(m.tools[1].argb, 0xFF1A1A1A);
      expect(m.tools[1].type, 'PETG');
      expect(m.toolSlot(1), 1);
    });

    test('PrusaSlicer M600 colour change: a new slot with the comment\'s colour', () {
      final m = parseGcode(_b('''
G90
M83
;LAYER_CHANGE
;Z:0.2
G1 X10 Y10 F3000
G1 X20 Y10 E1.0
;LAYER_CHANGE
;Z:0.4
;COLOR_CHANGE,T0,#8A2BE2
M600
G1 X20 Y20 E1.0
; filament_colour = #FFFFFF
'''));
      expect(m.layers[0].tool, [0]);
      expect(m.layers[1].tool, [1]);
      expect(m.tools.length, 2);
      expect(m.tools[0].argb, 0xFFFFFFFF); // the loaded filament, header
      expect(m.tools[1].argb, 0xFF8A2BE2); // the change's colour
      expect(m.tools[1].type, isNull);
      expect(m.isMultiTool, isTrue);
    });

    test('Orca manual filament change names its slot; a bare M600 takes the next', () {
      final m = parseGcode(_b('''
G90
M83
G1 X10 Y10 F3000
G1 X20 Y10 E1.0
; MANUAL_TOOL_CHANGE T2
M600
G1 X20 Y20 E1.0
M600
G1 X10 Y20 E1.0
'''));
      expect(m.layers[0].tool, [0, 2, 3]);
      expect(m.tools.map((t) => t.index), [0, 2, 3]);
      expect(m.toolSlot(3), 2);
      expect(m.hasSlicerColours, isFalse); // Cura-style: nothing in the file
    });

    test('single tool and a colour list shorter than the tools', () {
      final one = parseGcode(_b('''
G90
M83
G1 X10 Y10 F3000
G1 X20 Y10 E1.0
; filament_colour = #00FF00
'''));
      expect(one.isMultiTool, isFalse);
      expect(one.tools.length, 1);
      expect(one.tools[0].argb, 0xFF00FF00);

      final short = parseGcode(_b('''
G90
M83
G1 X10 Y10 F3000
T3
G1 X20 Y10 E1.0
T1
G1 X20 Y20 E1.0
; filament_colour = #FF0000;;bogus
'''));
      expect(short.tools.map((t) => t.index), [1, 3]);
      expect(short.tools[0].argb, isNull); // slot 1 is the empty entry
      expect(short.tools[1].argb, isNull); // slot 3 is past the list
      expect(short.hasSlicerColours, isFalse);
      expect(short.layers[0].tool, [3, 1]);
    });
  });
}
